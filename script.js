function changeLanguage(lang) {
    document.querySelectorAll('[data-key]').forEach(el => {
        const key = el.getAttribute('data-key');
        if (langData[lang][key]) {
            if (langData[lang][key].includes('<span')) {
                el.innerHTML = langData[lang][key];
            } else {
                el.innerText = langData[lang][key];
            }
        }
    });
    document.documentElement.lang = lang;
}

function toggleTab(type) {
    const truckContent = document.getElementById('content-trucks');
    const carContent = document.getElementById('content-cars');
    const tabTrucks = document.getElementById('tab-trucks');
    const tabCars = document.getElementById('tab-cars');

    if (type === 'trucks') {
        truckContent.classList.remove('hidden');
        carContent.classList.add('hidden');
        tabTrucks.classList.add('active-tab');
        tabCars.classList.remove('active-tab');
        tabCars.classList.add('text-gray-600');
    } else {
        truckContent.classList.add('hidden');
        carContent.classList.remove('hidden');
        tabCars.classList.add('active-tab');
        tabTrucks.classList.remove('active-tab');
        tabTrucks.classList.add('text-gray-600');
    }
}